const ALL = Object.entries(SKETCH_WORDS);

/** 서로 다른 카테고리에서 n개 뽑기 (최근에 나온 단어는 제외) */
export function pickWords(n = 3, recent: string[] = []): string[] {
  const cats = [...ALL].sort(() => Math.random() - 0.5).slice(0, n);
  return cats.map(([, words]) => {
    const pool = words.filter((w) => !recent.includes(w));
    const list = pool.length ? pool : words;
    return list[Math.floor(Math.random() * list.length)];
  });
}

/** 정답 비교용: 공백 제거, 소문자 */
export const normalizeAnswer = (s: string) => s.replace(/\s+/g, "").toLowerCase();

const CHO = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ";

/** 힌트 단계별 표시: 0 = 글자 수만, 1 = 첫 글자, 2 = 첫 글자 + 나머지 초성 */
export function hintOf(word: string, level: number): string {
  return [...word]
    .map((ch, i) => {
      if (ch === " ") return " ";
      if (level >= 1 && i === 0) return ch;
      if (level >= 2) {
        const code = ch.charCodeAt(0) - 0xac00;
        if (code >= 0 && code <= 11171) return CHO[Math.floor(code / 588)];
        return ch;
      }
      return "○";
    })
    .join("");
}
